import { IconX } from './Icons';
import { FormatsList, FORMATS_COUNT } from './FormatsList';

export function HelpModal({ open, onClose }: { open: boolean; onClose: () => void }) {
  if (!open) return null;
  return (
    <div className="drawer-backdrop" onClick={onClose}>
      <div className="modal" role="dialog" aria-label="Как загрузить в Sauda" onClick={(e) => e.stopPropagation()}>
        <div className="drawer__head">
          <h2>Как загрузить накладную в Sauda</h2>
          <button type="button" className="icon-btn" onClick={onClose} aria-label="Закрыть"><IconX /></button>
        </div>
        <p className="muted small">
          Сюда удобно попадать из Sauda: «Закупки» → «Приёмка» → кнопка «Из фото накладной».
        </p>
        <ol className="steps">
          <li>
            <b>Здесь:</b> добавьте фото, дождитесь распознавания и проверьте строки с жёлтой или красной пометкой.
            Главное — штрихкод, количество и цена. Если над таблицей зелёная плашка «Сходится с итогом», значит числа прочитаны верно.
            В Sauda уйдут только строки со штрихкодом: строку без штрихкода дополните, иначе её не будет в приёмке.
          </li>
          <li>
            Нажмите <b>«В Sauda»</b> — в новой вкладке откроется страница «Накладная из фото». Если вы не вошли в Sauda,
            сначала войдите — накладная откроется сразу после входа. Приёмка создаётся в магазине, выбранном в шапке Sauda.
          </li>
          <li>
            <b>В Sauda:</b> выберите поставщика (или создайте его из названия в накладной). Видно, какие товары нашлись в базе
            по штрихкоду, а каких нет: их Sauda создаст сама, если оставить галочку «Создать товары, которых нет в базе», иначе пропустит.
          </li>
          <li>
            Нажмите <b>«Создать приёмку»</b> — появится черновик с количеством и закупочными ценами.
          </li>
          <li>
            Проверьте черновик и нажмите <b>«Провести»</b>. Остатки меняются только после проведения.
          </li>
        </ol>
        <p className="muted small">
          Кнопки «Excel» и «Копировать» отдают те же строки файлом или через буфер обмена (штрихкод, количество, название, единица
          и цена приходная) — для архива или другой программы. Для Sauda они не нужны: хватает кнопки «В Sauda».
        </p>
        <h3>Если у поставщика нет штрихкодов в накладной</h3>
        <p>
          У части поставщиков в накладной свои коды товаров или кодов нет вовсе (см. список ниже). Для каждого нового кода введите штрихкод один раз —
          программа запомнит его и в следующих накладных подставит сама. Быстрее всего — загрузить каталог
          товаров из Sauda (Настройки → «Каталог Sauda»): тогда появятся подсказки по названию.
        </p>
        <h3>Какие накладные принимает система</h3>
        <p className="muted small">
          {FORMATS_COUNT} поставщиков настроены и проверены на реальных накладных. Поставщик определяется сам — по БИН или названию.
        </p>
        <FormatsList />
        <h3>Советы по фото</h3>
        <ul>
          <li>Лист целиком в кадре, снимайте сверху, без сильного наклона.</li>
          <li>Хорошее освещение без бликов и теней от телефона.</li>
          <li>Отправляйте оригинал фото, а не скриншот: сжатые мессенджером фото распознаются хуже.</li>
        </ul>
      </div>
    </div>
  );
}
