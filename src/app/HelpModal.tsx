import { IconX } from './Icons';

export function HelpModal({ open, onClose }: { open: boolean; onClose: () => void }) {
  if (!open) return null;
  return (
    <div className="drawer-backdrop" onClick={onClose}>
      <div className="modal" role="dialog" aria-label="Как загрузить в UMAG" onClick={(e) => e.stopPropagation()}>
        <div className="drawer__head">
          <h2>Как загрузить накладную в UMAG</h2>
          <button type="button" className="icon-btn" onClick={onClose} aria-label="Закрыть"><IconX /></button>
        </div>
        <ol className="steps">
          <li>
            <b>Здесь:</b> добавьте фото, дождитесь распознавания и проверьте строки с жёлтой или красной пометкой.
            Главное — штрихкод, количество и цена. Если над таблицей зелёная плашка «Сходится с итогом», значит числа прочитаны верно.
          </li>
          <li>
            Нажмите <b>«Excel для UMAG»</b> (скачается файл) или <b>«Копировать»</b>.
          </li>
          <li>
            <b>В UMAG:</b> «Закупки» → «Приёмка» → создайте приёмку, выберите поставщика и дату.
          </li>
          <li>
            Нажмите <b>«📥 Импорт товаров»</b>. Затем либо «Загрузить файл» и выберите скачанный файл,
            либо кликните в окно и нажмите <b>Ctrl+V</b>. Если UMAG спросит, как разделять, выберите <b>«Табуляция»</b>.
          </li>
          <li>
            Над столбцами выберите их назначение в том же порядке, что в настройках файла
            (по умолчанию: <b>Штрихкод</b>, <b>Количество</b>, <b>Название</b>, <b>Ед. изм</b>). Нажмите «Продолжить».
          </li>
          <li>
            Проверьте список и нажмите <b>«Провести»</b>.
          </li>
        </ol>
        <h3>Если у поставщика нет штрихкодов в накладной</h3>
        <p>
          У Мегаполиса и Сэт Колы в накладной свои коды товаров. Для каждого нового кода введите штрихкод один раз —
          программа запомнит его и в следующих накладных подставит сама. Быстрее всего — загрузить каталог
          товаров из UMAG (Настройки → «Каталог UMAG»): тогда появятся подсказки по названию.
        </p>
        <h3>Советы по фото</h3>
        <ul>
          <li>Лист целиком в кадре, снимайте сверху, без сильного наклона.</li>
          <li>Хорошее освещение без бликов и теней от телефона.</li>
          <li>Отправляйте оригинал фото, а не скриншот: сжатые мессенджером фото распознаются хуже.</li>
        </ul>
      </div>
    </div>
  );
}
