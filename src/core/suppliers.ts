/**
 * Справочник известных поставщиков и форматов их накладных.
 * Поставщик определяется по БИН (цифры OCR читает надёжнее всего) или по названию.
 * Чтобы добавить нового поставщика с накладной формы З-2 — достаточно новой записи.
 */

export type ParserId = 'z2' | 'setkola';

export interface Z2Options {
  /**
   * Какие коды стоят в строках товаров: штрихкоды EAN-8/13, коды поставщика
   * или никаких (тогда строки ищутся по столбцу сумм, а штрихкод — по названию)
   */
  code: 'ean' | 'digits' | 'none';
  /** Длина кода поставщика (для code = 'digits'), если известна */
  codeLength?: number;
  /**
   * Куда переносится длинное наименование относительно строки с кодом:
   * 'up' — первая часть названия выше кода (GRAND), 'down' — хвост ниже (Мегаполис).
   */
  nameDir: 'up' | 'down' | 'nearest';
  /**
   * Наименование слева от кода (форма З-2), справа (упаковочные листы, расходные накладные)
   * или штрихкод напечатан внутри наименования («… 95г / ШК: 4606779450709», Green House)
   */
  nameSide?: 'left' | 'right' | 'inline';
  /**
   * Между наименованием и кодом — столбец коротких номенклатурных номеров
   * («КЗ111», «ЯП104», «0349»), их не должно быть в наименовании
   */
  shortArticles?: boolean;
  /** Штрихкод не влез в ячейку: 12 цифр в строке кода, последняя цифра — строкой ниже (ЭльвиНиПлюс) */
  codeWrap?: boolean;
  /**
   * Наименования читаются отдельным проходом OCR по своему столбцу: на мятом или снятом под углом листе
   * с плотными двухстрочными названиями общий проход смешивает строки соседних товаров (ФудМастер)
   */
  nameStrip?: boolean;
  /** Копейки через дефис: «350-00», «10500-00» (Градус компани) */
  dashDecimals?: boolean;
  /**
   * Столбец «Приз» рядом с количеством: строка «Кол-во 0, Приз 6» — бесплатный товар.
   * Количество берётся из «Приз», цена и сумма — 0 (в «Итого к оплате» такие строки не входят)
   */
  prizeRows?: boolean;
  /**
   * Роли числовых столбцов слева направо, если их нельзя определить по арифметике (применяется, только
   * когда найдено ровно столько столбцов): 'qty' | 'qtyPlan' | 'price' | 'sum' | 'vat' | 'skip'
   */
  columns?: ('qty' | 'qtyPlan' | 'price' | 'sum' | 'vat' | 'skip')[];
  /** Цена напечатана парой «117 / 105,3» — без скидки и со скидкой: берётся вторая (с ней сходится «Сумма со скидкой») */
  slashPrice?: boolean;
  /**
   * Штрихкод напечатан внутри наименования, а следом идут срок годности, «н/ном» и NTIN (Табыс 2040). Строки при этом
   * ищутся по суммам (code: 'none'), наименование — текст до штрихкода; запасное прочтение — столбец «Штрих-код»
   * с перенесённой последней цифрой
   */
  barcodeInName?: boolean;
  /** Штрихкод — в последнем столбце, правее сумм; строки при этом ищутся по суммам (code: 'none') */
  barcodeRight?: boolean;
  /** Столбец «Ед. изм.» стоит между наименованием и штрихкодом (Сауда Дистрибьюшн) */
  unitBeforeCode?: boolean;
  /**
   * Где в строке стоят числа: на одной линии с кодом (center, по умолчанию),
   * внизу строки при коде у верхнего края (top) или на последней линии строки (bottom)
   */
  rowAlign?: 'center' | 'top' | 'bottom';
}

